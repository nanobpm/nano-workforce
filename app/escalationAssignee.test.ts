// Escalation user-task assignee: an unset assignee must leave the task UNASSIGNED, never raise an
// incident.
//
// The engine evaluates a `zeebe:assignmentDefinition assignee="=…"` expression with Zeebe's
// `evaluateStringExpression` semantics (nano-bpm #1398/#1421): a `null` result is an
// EXTRACT_VALUE_ERROR incident, while an EMPTY STRING means "unassigned". Every nwf escalation
// task used to end its assignee expression in `else null`, so every escalation raised with no
// configured `escalationAssignee` (the default) parked on an incident instead of reaching the
// operator's inbox (merlin, 21 Nov 2026: seven `human-escalation` instances).
//
// Class guard: EVERY assignee expression nwf emits — hand-authored in `resources/processes/*.bpmn`
// or generated by the delivery-graph compiler — must be the ONE canonical
// `ESCALATION_ASSIGNEE_FEEL`, and that expression is exercised on the real engine for every
// unset shape (absent, null, empty, whitespace) plus a set value.

import { after, test } from "node:test";
import { readdirSync, readFileSync } from "node:fs";
import { assert, assertEquals } from "#test-assert";
import { createWasmEngineClient, type WasmEngineClient } from "@nanobpm/urban-testkit";
import { ESCALATION_ASSIGNEE_FEEL } from "./escalationAssignee.ts";
import { compileDeliveryGraph } from "./deliveryGraphCompiler.ts";

const engines: WasmEngineClient[] = [];
after(async () => {
  await Promise.all(engines.map((e) => e.close()));
});

/** Decode the XML attribute escapes the BPMN files use inside an `assignee="…"` value. */
function unescapeXmlAttr(s: string): string {
  return s.replaceAll("&#34;", '"').replaceAll("&quot;", '"').replaceAll("&amp;", "&");
}

function assigneeExpressions(xml: string): string[] {
  // Either quote style: the compiler emits a single-quoted attribute when the value holds `"`.
  return [...xml.matchAll(/\bassignee=(?:"([^"]*)"|'([^']*)')/g)].map((m) => unescapeXmlAttr(m[1] ?? m[2] ?? ""));
}

function probeProcess(id: string, assignee: string): string {
  const attr = assignee.replaceAll("&", "&amp;").replaceAll('"', "&#34;");
  return `<?xml version="1.0" encoding="UTF-8"?>
<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" xmlns:zeebe="http://camunda.org/schema/zeebe/1.0" id="d_${id}" targetNamespace="http://nanobpm.io/test">
  <bpmn:process id="${id}" isExecutable="true">
    <bpmn:startEvent id="s"><bpmn:outgoing>f1</bpmn:outgoing></bpmn:startEvent>
    <bpmn:userTask id="t">
      <bpmn:extensionElements>
        <zeebe:userTask />
        <zeebe:assignmentDefinition candidateGroups="operators" assignee="${attr}" />
      </bpmn:extensionElements>
      <bpmn:incoming>f1</bpmn:incoming><bpmn:outgoing>f2</bpmn:outgoing>
    </bpmn:userTask>
    <bpmn:endEvent id="e"><bpmn:incoming>f2</bpmn:incoming></bpmn:endEvent>
    <bpmn:sequenceFlow id="f1" sourceRef="s" targetRef="t" />
    <bpmn:sequenceFlow id="f2" sourceRef="t" targetRef="e" />
  </bpmn:process>
</bpmn:definitions>`;
}

async function bootWith(xml: string, name: string): Promise<WasmEngineClient> {
  const engine = await createWasmEngineClient();
  engines.push(engine);
  await engine.deployResources([{ name, content: xml, contentType: "text/xml" }]);
  return engine;
}

async function settle(engine: WasmEngineClient, done: () => Promise<boolean>): Promise<void> {
  for (let i = 0; i < 200; i++) {
    if (await done()) return;
    await new Promise((r) => setTimeout(r, 10));
  }
}

const UNSET_SHAPES: { label: string; vars: Record<string, unknown> }[] = [
  { label: "absent", vars: {} },
  { label: "null", vars: { escalationAssignee: null } },
  { label: "empty", vars: { escalationAssignee: "" } },
  { label: "whitespace", vars: { escalationAssignee: "   " } },
  { label: "set", vars: { escalationAssignee: "alice" } },
];

for (const shape of UNSET_SHAPES) {
  test(`canonical escalation assignee (${shape.label}) creates the user task, never an incident`, async () => {
    const engine = await bootWith(probeProcess("assigneeProbe", ESCALATION_ASSIGNEE_FEEL), "probe.bpmn");
    await engine.createInstance({ processDefinitionId: "assigneeProbe", awaitCompletion: false, variables: shape.vars });
    await settle(engine, async () => (await engine.openUserTasks()).length > 0 || (await engine.searchIncidents()).length > 0);
    const incidents = await engine.searchIncidents();
    assertEquals(incidents.length, 0, `no incident; got ${JSON.stringify(incidents)}`);
    assertEquals((await engine.openUserTasks()).length, 1, "the escalation reaches the inbox");
  });
}

test("human-escalation with no configured assignee reaches the inbox (merlin 21 Nov 2026 regression)", async () => {
  const xml = readFileSync("resources/processes/human-escalation.bpmn", "utf8");
  const engine = await bootWith(xml, "human-escalation.bpmn");
  await engine.createInstance({
    processDefinitionId: "human-escalation",
    awaitCompletion: false,
    variables: { question: "q?", escalationAssignee: null, escalationSlaTimeout: "PT24H", answer: null },
  });
  await settle(engine, async () => (await engine.openUserTasks()).length > 0 || (await engine.searchIncidents()).length > 0);
  const incidents = await engine.searchIncidents();
  assertEquals(incidents.length, 0, `no incident; got ${JSON.stringify(incidents)}`);
  assertEquals((await engine.openUserTasks({ elementId: "escalation" })).length, 1);
});

test("every hand-authored assignee expression is the canonical ESCALATION_ASSIGNEE_FEEL", () => {
  const dir = "resources/processes";
  const found: string[] = [];
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".bpmn"))) {
    for (const expr of assigneeExpressions(readFileSync(`${dir}/${f}`, "utf8"))) {
      found.push(f);
      assertEquals(expr, ESCALATION_ASSIGNEE_FEEL, `${f}: assignee expression drifted from ESCALATION_ASSIGNEE_FEEL`);
    }
  }
  assert(found.length >= 3, `expected the escalation tasks to be scanned; found ${found.join(", ")}`);
});

test("the delivery-graph compiler's human node uses the canonical ESCALATION_ASSIGNEE_FEEL", async () => {
  const r = await compileDeliveryGraph({
    nodes: [{ id: "h", kind: "human", human: { prompt: "approve?" } }],
    edges: [],
  });
  assert(r.ok, `compile failed: ${JSON.stringify(r)}`);
  const exprs = assigneeExpressions(r.bpmn);
  assert(exprs.length > 0, "the compiled human node carries an assignee");
  for (const e of exprs) assertEquals(e, ESCALATION_ASSIGNEE_FEEL);
});
